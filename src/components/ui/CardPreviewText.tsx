import React from 'react';
import { AppText } from './AppText';

/**
 * `AppText`-дублікат з жорстко вимкненим `allowFontScaling` (POLYTSIA V1.6.1, Фаза 22,
 * `docs/A11Y_LARGE_TEXT_AUDIT.md`) — ЄДИНИЙ виняток із правила "весь текст застосунку
 * масштабується за системним розміром шрифту" (`AppText` сама по собі його ніде не вимикає).
 *
 * Використовується виключно всередині трьох shareable-карток фіксованого формату
 * (`MemoryCardPreview`/`SeasonCardPreview`/`FingerprintCardPreview`) — кожна з них `width:
 * '100%', aspectRatio: N, overflow: 'hidden'`, захоплюється `react-native-view-shot` у PNG
 * для "Поділитися"/"Зберегти в галерею". Це не звичайний скролований екран — це шаблон
 * зображення з наперед розрахованою композицією (кілька текстових блоків, стек іконок,
 * колаж обкладинок). При збільшеному системному розмірі шрифту (Dynamic Type/Android "великий
 * текст", аж до accessibility-діапазону) сукупна висота текстових блоків усередині
 * фіксованого `aspectRatio`-контейнера могла б перевищити висоту картки — `overflow: 'hidden'`
 * тоді обрізає цілі секції (не лише один рядок), а не рівно те, що обрізав би звичайний
 * `numberOfLines` на одному елементі.
 *
 * Тому картки — свідомий і єдиний виняток: текст усередині НЕ масштабується, і картка завжди
 * лишається тим самим зображенням, яке бачив користувач у превʼю, що й потрапляє у файл
 * поширення. Решта застосунку (усі звичайні екрани) використовують `AppText` напряму й
 * повністю підтримують системне масштабування — обмеження стосується лише цих трьох
 * компонентів-шаблонів.
 */
export function CardPreviewText(props: React.ComponentProps<typeof AppText>) {
  return <AppText {...props} allowFontScaling={false} />;
}
