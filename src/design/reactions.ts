import type { ComponentProps } from 'react';
import type { Ionicons } from '@expo/vector-icons';

type IconName = ComponentProps<typeof Ionicons>['name'];

/**
 * Реакції на запис щоденника (Milestone 11, доповнення — власник продукту, ідея з референсом):
 * маленький "настрій" на нотатку/цитату — ОДНА з 7 фіксованих реакцій, необов'язкова, без
 * довільного тексту. Свідомо НЕ система тегів (довільна, багато-до-багатьох) — рівно одна
 * реакція на запис, той самий "просто optional reaction", про який прямо попросив власник
 * продукту, а не ще один шар вільної категоризації поверх уже наявних типів нотаток
 * (`NoteType`) і власних категорій (`note_category`).
 *
 * Зберігається в уже наявній, свідомо НЕ CHECK-обмеженій колонці `note.reaction`/
 * `quote.reaction` (`003_journal_entry_extensions.ts`, Фаза 1 M11) — той коментар прямо казав
 * "список реакцій ще узгоджується з користувачем на етапі UI (Фаза 3+)"; це саме той момент.
 * Тому МІГРАЦІЯ НЕ ПОТРІБНА — лише ця константа й UI, що її використовує.
 *
 * Значення (ключі) стабільні рядки, не enum-індекси — та сама причина, що й усюди в цій БД:
 * колонка лишається plain TEXT, список тут можна розширити пізніше без нової міграції; старі/
 * нерозпізнані значення `isReactionId` відфільтровує, а не кидає — той самий підхід, що вже є
 * для `note.type`/категорій (`resolveEntryTypeLabel`, "невідоме значення = показати без
 * позначки", а не крашнути екран).
 *
 * Іконки — `Ionicons`, НЕ сирі emoji-гліфи (той самий вибір, що й доповнення12 для чипів
 * фільтра бібліотеки: тісніший контроль розміру/кольору, узгоджений рендер на будь-якому
 * пристрої/ОС, а не залежність від того, які emoji-гліфи встановлені в системі). Кожна іконка
 * навмисно ОБРАНА так, щоб не збігатись із уже зайнятими значками того самого контексту
 * (запис щоденника): `heart`/`heart-outline` — вже "обране" (`isFavorite`, окрема, давніша
 * позначка), `sparkles-outline` — вже заголовок секції "Спогад про книгу", `star`/`star-half`
 * — вже зірочки оцінки книги (`StarRating`).
 */
export type ReactionId = 'cute' | 'funny' | 'sad' | 'shock' | 'favorite' | 'question' | 'strong';

export interface ReactionMeta {
  icon: IconName;
  label: string;
}

export const REACTION_META: Record<ReactionId, ReactionMeta> = {
  cute: { icon: 'rose-outline', label: 'Мило' },
  funny: { icon: 'happy-outline', label: 'Смішно' },
  sad: { icon: 'sad-outline', label: 'Сумно' },
  shock: { icon: 'alert-circle-outline', label: 'Шок' },
  favorite: { icon: 'star-outline', label: 'Улюблене' },
  question: { icon: 'help-circle-outline', label: 'Питання' },
  strong: { icon: 'flame-outline', label: 'Сильний момент' },
};

/** Порядок показу в рядку вибору — той самий порядок, що й у референсі власника продукту. */
export const REACTION_ORDER: ReactionId[] = ['cute', 'funny', 'sad', 'shock', 'favorite', 'question', 'strong'];

/** Форми "N ..." для агрегованої статистики щоденника (`pluralizeUk`, той самий 3-формний
 * патерн, що й `DAY_FORMS`/`ENTRY_FORMS` по всьому застосунку) — в українській узгоджується й
 * прикметник, і іменник ("1 милий момент" / "2 милі моменти" / "5 милих моментів"), тому тут
 * повні словосполучення, а не лише слово "момент". */
export const REACTION_COUNT_FORMS: Record<ReactionId, readonly [string, string, string]> = {
  cute: ['милий момент', 'милі моменти', 'милих моментів'],
  funny: ['смішний момент', 'смішні моменти', 'смішних моментів'],
  sad: ['сумний момент', 'сумні моменти', 'сумних моментів'],
  shock: ['шокуючий момент', 'шокуючі моменти', 'шокуючих моментів'],
  favorite: ['улюблений момент', 'улюблені моменти', 'улюблених моментів'],
  question: ['незрозумілий момент', 'незрозумілі моменти', 'незрозумілих моментів'],
  strong: ['сильний момент', 'сильні моменти', 'сильних моментів'],
};

/** `reaction` — вільний `TEXT` без CHECK у БД (навмисно, докладніше вище) — тому будь-яке
 * значення, прочитане з БД, потребує явної перевірки перед використанням як ключ
 * `REACTION_META`/`REACTION_COUNT_FORMS`, а не припущення "це напевно один із семи". Той самий
 * захисний патерн, що й `normalizeShelfThemeId`/категорії нотаток: нерозпізнане значення (майбутня
 * версія застосунку додала реакцію, якої ця версія ще не знає, або просто пошкоджені дані) —
 * тихо "без реакції" в UI, а не крах екрана. */
export function isReactionId(value: string): value is ReactionId {
  return (REACTION_ORDER as string[]).includes(value);
}
