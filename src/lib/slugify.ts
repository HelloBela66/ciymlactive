/**
 * Дуже проста слагіфікація — потрібна лише як стабільний UNIQUE-ключ для дедуплікації
 * жанрів (`genre.slug`, `docs/DATABASE.md`), ніде не показується користувачу й не бере
 * участі в URL, тому не вимагає транслітерації кирилиці в латиницю: просто нормалізований,
 * пробіло-незалежний варіант того самого імені. Два різні написання того самого жанру
 * ("Наукова фантастика" / "наукова  фантастика") дають однаковий slug.
 */
export function slugify(input: string): string {
  return input
    .trim()
    .toLowerCase()
    .replace(/['"«»]/g, '')
    .replace(/[\s/]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '');
}
