import type { RawProviderBook } from './BookMetadataProvider';

/**
 * Українська пошукова політика (Milestone 7.1, за прямим проханням користувача після
 * реального тесту: ISBNdb повернув запис з `language: 'ukrainian'`, але `title` лишився
 * англійським — "IF WE WERE VILLAINS (Ukrainian language)" — тобто поле мови саме по собі
 * НЕ надійне; його не можна використовувати як єдиний критерій).
 *
 * Мета (дослівно від користувача): "нужно чтобы приложение работало так чтобы находило
 * только УКРАИНСКИЕ книги, пока приоритет стоит исключительно на украинские издательства."
 * Тобто застосунок має показувати в пошуку лише видання, які справді українською —
 * а не будь-яке видання книги (оригінал, англійський переклад тощо), яке провайдер вважає
 * релевантним запиту.
 *
 * Підхід — подвійна перевірка, а не довіра жодному єдиному полю:
 * 1) поле мови від провайдера каже "українська" (коди різняться між провайдерами: `uk`
 *    (ISO 639-1, Google Books/ISBNdb), `ukr` (ISO 639-2, Open Library), або повне слово);
 * 2) І сама назва взагалі містить кирилицю (а не лишень латиницю) — підстраховка саме проти
 *    того конкретного випадку: не-кириличної назви з хибно проставленою міткою "мова:
 *    українська". Навмисно НЕ звужено до літер, унікальних для української абетки (і, ї, є,
 *    ґ) — багато цілком українських назв їх не містить ("Кобзар", "Сонце" тощо), і звужений
 *    варіант відсіював би їх хибно-негативно; розрізнення "українська проти російська" тут
 *    не мета — лише "кирилиця проти щось геть іншою мовою під хибною міткою".
 *
 * Обидві умови мають виконуватись одночасно — це свідомо консервативний фільтр (краще
 * пропустити межовий випадок, ніж показати користувачу нерелевантну книгу іноземною мовою,
 * що й було прямою скаргою).
 */

const UKRAINIAN_LANGUAGE_TOKENS = ['uk', 'ukr', 'ukrainian', 'українська', 'укр'];

const HAS_CYRILLIC = /[Ѐ-ӿ]/;

function normalizeLanguageTag(language: string | undefined): string {
  return (language ?? '').trim().toLowerCase();
}

function languageTagSaysUkrainian(language: string | undefined): boolean {
  const normalized = normalizeLanguageTag(language);
  if (normalized.length === 0) return false;
  return UKRAINIAN_LANGUAGE_TOKENS.some((token) => normalized === token || normalized.startsWith(`${token}-`));
}

/**
 * `true`, якщо видання достатньо впевнено виглядає українськомовним, щоб показати його в
 * результатах пошуку/сканування. Навмисно НЕ єдине джерело істини для збереження книги —
 * користувач завжди може вручну додати книгу будь-якою мовою (`ManualBookProvider`,
 * "Додати вручну" завжди доступні) чи виправити мову на екрані підтвердження імпорту.
 */
export function isLikelyUkrainianBook(book: RawProviderBook): boolean {
  if (!languageTagSaysUkrainian(book.language)) return false;
  return HAS_CYRILLIC.test(book.title);
}

/** Фільтрує масив результатів провайдера, лишаючи лише ті, що проходять
 * {@link isLikelyUkrainianBook}. */
export function filterUkrainianBooks(books: RawProviderBook[]): RawProviderBook[] {
  return books.filter(isLikelyUkrainianBook);
}

/**
 * Слабший сигнал, ніж {@link isLikelyUkrainianBook} — лише кирилична назва, БЕЗ вимоги до
 * мовної мітки від провайдера. Для звичайного пошуку (`app/(tabs)/search.tsx`) подвійна
 * перевірка вище лишається єдиною політикою (свідоме рішення Milestone 7.1, не чіпається).
 * Але для «Що почитати завтра?» (Milestone 11, доповнення, `useTomorrowRecommendation.ts`)
 * — реальний тест на пристрої показав, що для типових жанрів подвійний фільтр інколи
 * відсіює геть усе (мовна мітка Google Books для українських видань нерідко відсутня чи
 * неточна — той самий клас проблеми, що й спричинив появу основного фільтра), лишаючи
 * користувача без жодної відповіді. Тут порожній результат гірший за менш певний — тож ця
 * функція обслуговує ДРУГИЙ рівень (не заміну) кількарівневого каскаду: спершу
 * `isLikelyUkrainianBook`, і лише коли він не дав жодного кандидата — цей слабший фільтр;
 * екран результату явно позначає, коли впевненості в мові видання менше.
 */
export function hasCyrillicTitle(book: RawProviderBook): boolean {
  return HAS_CYRILLIC.test(book.title);
}
